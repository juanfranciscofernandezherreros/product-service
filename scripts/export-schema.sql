-- =====================================================================
--  Exporta el DDL del schema "public" leyendo pg_catalog.
--  Devuelve una fila por tabla (ordenadas por nombre) con su CREATE TABLE:
--  columnas, tipos, NOT NULL, DEFAULT, identidad y restricciones
--  CHECK / PRIMARY KEY / UNIQUE / FOREIGN KEY (en ese orden y, dentro de
--  cada tipo, por nombre: asi el resultado es estable entre ejecuciones).
--
--  Solo lee el catalogo: no modifica nada ni toca datos.
--  Uso normal:  python scripts/export_supabase_schema.py
--  Tambien se puede pegar tal cual en el SQL Editor de Supabase.
-- =====================================================================
SET search_path = public;

SELECT 'CREATE TABLE ' || quote_ident(c.relname) || ' (' || E'\n'
    || (
        SELECT string_agg(
                   '    ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
                   || CASE
                          WHEN a.attgenerated = 's'
                              THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                          ELSE ''
                      END
                   || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
                   || CASE a.attidentity
                          WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                          WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                          ELSE ''
                      END
                   || CASE
                          WHEN d.adbin IS NOT NULL AND a.attgenerated = ''
                              THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
                          ELSE ''
                      END,
                   E',\n' ORDER BY a.attnum)
        FROM pg_attribute a
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    )
    || COALESCE((
        SELECT E',\n' || string_agg(
                   '    CONSTRAINT ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid),
                   E',\n' ORDER BY array_position(ARRAY['c', 'p', 'u', 'f'], k.contype::text), k.conname)
        FROM pg_constraint k
        WHERE k.conrelid = c.oid AND k.contype IN ('c', 'p', 'u', 'f')
    ), '')
    || E'\n);\n' AS ddl
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
ORDER BY c.relname;
